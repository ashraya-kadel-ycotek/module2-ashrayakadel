-- ======================================================================
-- RETAIL SNOWFLAKE SCHEMA: tables + date seed (2026-01-01 .. 2035-12-31)
-- Safe to rerun: CREATE ... IF NOT EXISTS, and the seed only INSERTS missing rows.
-- Week convention: ISO (Monday start). A week belongs to the month of its THURSDAY.
-- FCT_SALES_PER_WEEK aggregate: grain = week / item / location (no customer).
-- All objects are FULLY QUALIFIED (MODULE2_ETL.GOLD.<table>).
-- No SET variables. No BEGIN TRANSACTION wrapper (Airflow split_statements safe).
--
-- Surrogate keys: AUTOINCREMENT — load scripts MUST NOT supply _KY on INSERT.
-- BATCH_ID is DATE (matches bronze/silver).
-- ======================================================================


