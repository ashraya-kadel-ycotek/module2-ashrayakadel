          ON pw.WEEK_ID = YEAROFWEEKISO(dt) * 100 + WEEKISO(dt)
         AND pw.CURR_FLG = TRUE
        ORDER BY dt
      ) s
   ON t.DAY_ID = s.DAY_ID
WHEN NOT MATCHED THEN INSERT (DAY_ID, CALENDAR_DT, DAY_OF_WEEK_NUMBER, DAY_OF_MONTH_NUMBER, WEEKEND_FLG, WEEK_KY, REC_INS_TS, REC_UPDT_TS, SRC_SYS_CD, BATCH_ID, EFF_FROM_DATE, EFF_TO_DATE, CURR_FLG)
