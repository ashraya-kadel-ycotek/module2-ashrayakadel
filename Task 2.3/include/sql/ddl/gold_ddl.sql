-- DIM_MONTH
MERGE INTO MODULE2_ETL.GOLD.DIM_MONTH t
USING (
        WITH n AS (
            SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS i
            FROM TABLE(GENERATOR(ROWCOUNT => 20000))
        ),
        d AS (
            SELECT DATEADD(DAY, i, TO_DATE('2026-01-01')) AS dt
            FROM n
            WHERE DATEADD(DAY, i, TO_DATE('2026-01-01')) <= TO_DATE('2035-12-31')
        ),
        wk AS (
            SELECT YEAROFWEEKISO(dt) AS wy,
                   WEEKISO(dt)       AS wn,
                   MIN(DATEADD(DAY, 1 - DAYOFWEEKISO(dt), dt)) AS wstart
            FROM d
            GROUP BY YEAROFWEEKISO(dt), WEEKISO(dt)
        ),
        mth AS (
            SELECT DATE_TRUNC('MONTH', dt) AS m FROM d
            UNION
            SELECT DATE_TRUNC('MONTH', DATEADD(DAY, 3, wstart)) FROM wk
        ),
        qtr AS (SELECT DISTINCT DATE_TRUNC('QUARTER', m) AS q FROM mth),
        yr  AS (SELECT DISTINCT DATE_TRUNC('YEAR', q)    AS y FROM qtr)
        SELECT YEAR(m) * 100 + MONTH(m) AS MONTH_ID,
               DECODE(MONTH(m), 1,'January',2,'February',3,'March',4,'April',5,'May',6,'June',7,'July',8,'August',9,'September',10,'October',11,'November',12,'December') AS MONTH_NAME,
               MONTH(m) AS MONTH_NUMBER,
               DAY(LAST_DAY(m)) AS DAYS_IN_MONTH_NUMBER,
               pq.QUARTER_KY
        FROM mth
        JOIN MODULE2_ETL.GOLD.DIM_QUARTER pq ON pq.QUARTER_ID = YEAR(m) * 10 + QUARTER(m) AND pq.CURR_FLG = TRUE
        ORDER BY m
      ) s
   ON t.MONTH_ID = s.MONTH_ID
WHEN NOT MATCHED THEN INSERT (MONTH_ID, MONTH_NAME, MONTH_NUMBER, DAYS_IN_MONTH_NUMBER, QUARTER_KY, REC_INS_TS, REC_UPDT_TS, SRC_SYS_CD, BATCH_ID, EFF_FROM_DATE, EFF_TO_DATE, CURR_FLG)
VALUES (s.MONTH_ID, s.MONTH_NAME, s.MONTH_NUMBER, s.DAYS_IN_MONTH_NUMBER, s.QUARTER_KY, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP(), 'DATE_SEED', CURRENT_DATE(), DATE '1900-01-01', DATE '9999-12-31', TRUE);

