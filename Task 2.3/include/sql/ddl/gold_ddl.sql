        ),
        mth AS (
            SELECT DATE_TRUNC('MONTH', dt) AS m FROM d
            UNION
            SELECT DATE_TRUNC('MONTH', DATEADD(DAY, 3, wstart)) FROM wk
        ),
        qtr AS (SELECT DISTINCT DATE_TRUNC('QUARTER', m) AS q FROM mth),
        yr  AS (SELECT DISTINCT DATE_TRUNC('YEAR', q)    AS y FROM qtr)
        SELECT wy * 100 + wn AS WEEK_ID,
               wstart AS WEEK_START_DT,
               DATEADD(DAY, 6, wstart) AS WEEK_END_DT,
               wn AS WEEK_OF_YEAR_NUMBER,
               pm.MONTH_KY
        FROM wk
        JOIN MODULE2_ETL.GOLD.DIM_MONTH pm
          ON pm.MONTH_ID = YEAR(DATEADD(DAY, 3, wstart)) * 100 + MONTH(DATEADD(DAY, 3, wstart))
         AND pm.CURR_FLG = TRUE
        ORDER BY wstart
      ) s
   ON t.WEEK_ID = s.WEEK_ID
WHEN NOT MATCHED THEN INSERT (WEEK_ID, WEEK_START_DT, WEEK_END_DT, WEEK_OF_YEAR_NUMBER, MONTH_KY, REC_INS_TS, REC_UPDT_TS, SRC_SYS_CD, BATCH_ID, EFF_FROM_DATE, EFF_TO_DATE, CURR_FLG)
