-- ======================================================================
-- DATE SEED (insert-only, individually idempotent MERGE statements)
-- BATCH_ID is DATE — seed writes CURRENT_DATE().
-- Order matters: YEAR -> QUARTER -> MONTH -> WEEK -> DAY (each joins parent _KY).
-- ======================================================================

-- DIM_YEAR
MERGE INTO MODULE2_ETL.GOLD.DIM_YEAR t
USING (
        WITH n AS (
            SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS i
            FROM TABLE(GENERATOR(ROWCOUNT => 20000))
        ),
        d AS (
            SELECT DATEADD(DAY, i, TO_DATE('2026-01-01')) AS dt
            FROM n
            WHERE DATEADD(DAY, i, TO_DATE('2026-01-01')) <= TO_DATE('2035-12-31')
        ),
        wk AS (
            SELECT YEAROFWEEKISO(dt) AS wy,
                   WEEKISO(dt)       AS wn,
                   MIN(DATEADD(DAY, 1 - DAYOFWEEKISO(dt), dt)) AS wstart
            FROM d
            GROUP BY YEAROFWEEKISO(dt), WEEKISO(dt)
        ),
        mth AS (
            SELECT DATE_TRUNC('MONTH', dt) AS m FROM d
            UNION
            SELECT DATE_TRUNC('MONTH', DATEADD(DAY, 3, wstart)) FROM wk
        ),
        qtr AS (SELECT DISTINCT DATE_TRUNC('QUARTER', m) AS q FROM mth),
        yr  AS (SELECT DISTINCT DATE_TRUNC('YEAR', q)    AS y FROM qtr)
        SELECT YEAR(y) AS YEAR_ID,
               YEAR(y) AS CALENDAR_YEAR,
               ((YEAR(y) % 4 = 0 AND YEAR(y) % 100 <> 0) OR YEAR(y) % 400 = 0) AS LEAP_YEAR_FLG,
               'FY' || TO_VARCHAR(YEAR(y)) AS FISCAL_YEAR_LABEL
        FROM yr
        ORDER BY y
      ) s
   ON t.YEAR_ID = s.YEAR_ID
WHEN NOT MATCHED THEN INSERT (YEAR_ID, CALENDAR_YEAR, LEAP_YEAR_FLG, FISCAL_YEAR_LABEL, REC_INS_TS, REC_UPDT_TS, SRC_SYS_CD, BATCH_ID, EFF_FROM_DATE, EFF_TO_DATE, CURR_FLG)
VALUES (s.YEAR_ID, s.CALENDAR_YEAR, s.LEAP_YEAR_FLG, s.FISCAL_YEAR_LABEL, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP(), 'DATE_SEED', CURRENT_DATE(), DATE '1900-01-01', DATE '9999-12-31', TRUE);

-- DIM_QUARTER
MERGE INTO MODULE2_ETL.GOLD.DIM_QUARTER t
USING (
        WITH n AS (
            SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS i
            FROM TABLE(GENERATOR(ROWCOUNT => 20000))
        ),
        d AS (
            SELECT DATEADD(DAY, i, TO_DATE('2026-01-01')) AS dt
            FROM n
            WHERE DATEADD(DAY, i, TO_DATE('2026-01-01')) <= TO_DATE('2035-12-31')
        ),
        wk AS (
            SELECT YEAROFWEEKISO(dt) AS wy,
                   WEEKISO(dt)       AS wn,
                   MIN(DATEADD(DAY, 1 - DAYOFWEEKISO(dt), dt)) AS wstart
            FROM d
            GROUP BY YEAROFWEEKISO(dt), WEEKISO(dt)
        ),
        mth AS (
            SELECT DATE_TRUNC('MONTH', dt) AS m FROM d
            UNION
            SELECT DATE_TRUNC('MONTH', DATEADD(DAY, 3, wstart)) FROM wk
        ),
        qtr AS (SELECT DISTINCT DATE_TRUNC('QUARTER', m) AS q FROM mth),
        yr  AS (SELECT DISTINCT DATE_TRUNC('YEAR', q)    AS y FROM qtr)
        SELECT YEAR(q) * 10 + QUARTER(q) AS QUARTER_ID,
               QUARTER(q) AS QUARTER_NUMBER,
               'Q' || TO_VARCHAR(QUARTER(q)) || ' ' || TO_VARCHAR(YEAR(q)) AS QUARTER_NAME,
               py.YEAR_KY
        FROM qtr
