        MD5(
            COALESCE(s.TRANSACTION_ID,'')||'|'||
            TO_VARCHAR(TRY_TO_NUMBER(s.TRANSACTION_LINE_NUMBER))||'|'||
            TO_VARCHAR(TRY_TO_DATE(s.SALES_DT,'YYYY-MM-DD'))||'|'||
            COALESCE(s.ITEM_ID,'')||'|'||COALESCE(s.LOCATION_ID,'')||'|'||
            COALESCE(s.CUSTOMER_ID,'')||'|'||COALESCE(s.CUSTOMER_NAME,'')||'|'||
            COALESCE(s.CUSTOMER_EMAIL,'')||'|'||COALESCE(s.CUSTOMER_PHONE,'')||'|'||
