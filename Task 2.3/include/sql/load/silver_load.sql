-- 3.6 MERGE
MERGE INTO silver.TMP_INVENTORY_MASTER t
USING (
    SELECT
        TRY_TO_DATE(s.INVENTORY_DT,'YYYY-MM-DD') AS INVENTORY_DT,
        s.ITEM_ID, s.LOCATION_ID,
        TRY_TO_NUMBER(s.STOCK_ON_HAND) AS STOCK_ON_HAND,
        TRY_TO_NUMBER(s.IN_TRANSIT)    AS IN_TRANSIT,
        s.SRC_FILE_NM,
        MD5(
            TO_VARCHAR(TRY_TO_DATE(s.INVENTORY_DT,'YYYY-MM-DD'))||'|'||
            COALESCE(s.ITEM_ID,'')||'|'||COALESCE(s.LOCATION_ID,'')||'|'||
            TO_VARCHAR(TRY_TO_NUMBER(s.STOCK_ON_HAND))||'|'||
            TO_VARCHAR(TRY_TO_NUMBER(s.IN_TRANSIT))
        ) AS ROW_HASH
    FROM bronze.STG_INVENTORY_MASTER s
    WHERE s.BATCH_ID = DATE '{{ ds }}'
      AND TRY_TO_DATE(s.INVENTORY_DT,'YYYY-MM-DD') IS NOT NULL
      AND TRY_TO_NUMBER(s.STOCK_ON_HAND) IS NOT NULL
      AND TRY_TO_NUMBER(s.IN_TRANSIT)    IS NOT NULL
      AND TRY_TO_NUMBER(s.STOCK_ON_HAND) >= 0
      AND TRY_TO_NUMBER(s.IN_TRANSIT)    >= 0
      AND s.ITEM_ID IS NOT NULL AND s.LOCATION_ID IS NOT NULL
      AND EXISTS (SELECT 1 FROM silver.TMP_ITEM_MASTER  i WHERE i.ITEM_ID     = s.ITEM_ID)
      AND EXISTS (SELECT 1 FROM silver.TMP_STORE_MASTER st WHERE st.LOCATION_ID = s.LOCATION_ID)
      AND NOT EXISTS (
          SELECT 1 FROM (
              SELECT TRY_TO_DATE(INVENTORY_DT,'YYYY-MM-DD') AS D,
                     ITEM_ID, LOCATION_ID, COUNT(*) c
              FROM bronze.STG_INVENTORY_MASTER
              WHERE BATCH_ID = DATE '{{ ds }}'
              GROUP BY 1,2,3
          ) d
          WHERE d.D = TRY_TO_DATE(s.INVENTORY_DT,'YYYY-MM-DD')
            AND d.ITEM_ID = s.ITEM_ID
            AND d.LOCATION_ID = s.LOCATION_ID
            AND d.c > 1
      )
) s
ON  t.INVENTORY_DT = s.INVENTORY_DT
AND t.ITEM_ID      = s.ITEM_ID
AND t.LOCATION_ID  = s.LOCATION_ID
WHEN MATCHED AND t._ROW_HASH <> s.ROW_HASH THEN UPDATE SET
    STOCK_ON_HAND = s.STOCK_ON_HAND, IN_TRANSIT = s.IN_TRANSIT,
    _SRC_FILE_NM = s.SRC_FILE_NM, _BATCH_ID = DATE '{{ ds }}',
    _LOAD_TS = CURRENT_TIMESTAMP(), _ROW_HASH = s.ROW_HASH
WHEN NOT MATCHED THEN INSERT
    (INVENTORY_DT, ITEM_ID, LOCATION_ID, STOCK_ON_HAND, IN_TRANSIT,
     _SRC_FILE_NM, _BATCH_ID, _LOAD_TS, _ROW_HASH)
    VALUES
    (s.INVENTORY_DT, s.ITEM_ID, s.LOCATION_ID, s.STOCK_ON_HAND, s.IN_TRANSIT,
     s.SRC_FILE_NM, DATE '{{ ds }}', CURRENT_TIMESTAMP(), s.ROW_HASH);

