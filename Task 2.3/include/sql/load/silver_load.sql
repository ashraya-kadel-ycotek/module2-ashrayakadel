    ITEM_ID = s.ITEM_ID,
    LOCATION_ID = s.LOCATION_ID,
    CUSTOMER_ID = s.CUSTOMER_ID,
    CUSTOMER_NAME = s.CUSTOMER_NAME,
    CUSTOMER_EMAIL = s.CUSTOMER_EMAIL,
    CUSTOMER_PHONE = s.CUSTOMER_PHONE,
    SLS_QTY = s.SLS_QTY,
    SLS_AMT = s.SLS_AMT,
    _SRC_FILE_NM = s.SRC_FILE_NM,
    _BATCH_ID = DATE '{{ ds }}',
    _LOAD_TS = CURRENT_TIMESTAMP(),
    _ROW_HASH = s.ROW_HASH
WHEN NOT MATCHED THEN INSERT
    (TRANSACTION_ID, TRANSACTION_LINE_NUMBER, SALES_DT, ITEM_ID, LOCATION_ID,
     CUSTOMER_ID, CUSTOMER_NAME, CUSTOMER_EMAIL, CUSTOMER_PHONE, SLS_QTY, SLS_AMT,
     _SRC_FILE_NM, _BATCH_ID, _LOAD_TS, _ROW_HASH)
VALUES
    (s.TRANSACTION_ID, s.TRANSACTION_LINE_NUMBER, s.SALES_DT, s.ITEM_ID, s.LOCATION_ID,
     s.CUSTOMER_ID, s.CUSTOMER_NAME, s.CUSTOMER_EMAIL, s.CUSTOMER_PHONE, s.SLS_QTY, s.SLS_AMT,
     s.SRC_FILE_NM, DATE '{{ ds }}', CURRENT_TIMESTAMP(), s.ROW_HASH);

