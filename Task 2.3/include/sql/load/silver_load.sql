-- 1.3 MERGE
MERGE INTO silver.TMP_STORE_MASTER t
USING (
    SELECT
        s.LOCATION_ID, s.LOCATION_NAME, s.ADDRESS_LINE,
        s.DISTRICT_ID, s.DISTRICT_NAME, s.DISTRICT_CODE,
        s.STATE_ID, s.STATE_NAME, s.STATE_CODE,
        s.SRC_FILE_NM,
        MD5(
            COALESCE(s.LOCATION_ID  ,'')||'|'||COALESCE(s.LOCATION_NAME ,'')||'|'||
            COALESCE(s.ADDRESS_LINE ,'')||'|'||COALESCE(s.DISTRICT_ID   ,'')||'|'||
            COALESCE(s.DISTRICT_NAME,'')||'|'||COALESCE(s.DISTRICT_CODE ,'')||'|'||
            COALESCE(s.STATE_ID     ,'')||'|'||COALESCE(s.STATE_NAME    ,'')||'|'||
            COALESCE(s.STATE_CODE   ,'')
        ) AS ROW_HASH
    FROM bronze.STG_STORE_MASTER s
    WHERE s.BATCH_ID = DATE '{{ ds }}'
      AND s.LOCATION_ID IS NOT NULL AND s.LOCATION_NAME IS NOT NULL
      AND s.ADDRESS_LINE IS NOT NULL AND s.DISTRICT_ID IS NOT NULL
      AND s.DISTRICT_NAME IS NOT NULL AND s.DISTRICT_CODE IS NOT NULL
      AND s.STATE_ID IS NOT NULL AND s.STATE_NAME IS NOT NULL
      AND s.STATE_CODE IS NOT NULL
      AND s.LOCATION_ID NOT IN (
          SELECT LOCATION_ID FROM bronze.STG_STORE_MASTER
          WHERE BATCH_ID = DATE '{{ ds }}' AND LOCATION_ID IS NOT NULL
          GROUP BY LOCATION_ID HAVING COUNT(*) > 1
      )
) s
ON t.LOCATION_ID = s.LOCATION_ID
WHEN MATCHED AND t._ROW_HASH <> s.ROW_HASH THEN UPDATE SET
    LOCATION_NAME = s.LOCATION_NAME, ADDRESS_LINE = s.ADDRESS_LINE,
    DISTRICT_ID = s.DISTRICT_ID, DISTRICT_NAME = s.DISTRICT_NAME,
    DISTRICT_CODE = s.DISTRICT_CODE, STATE_ID = s.STATE_ID,
    STATE_NAME = s.STATE_NAME, STATE_CODE = s.STATE_CODE,
    _SRC_FILE_NM = s.SRC_FILE_NM, _BATCH_ID = DATE '{{ ds }}',
    _LOAD_TS = CURRENT_TIMESTAMP(), _ROW_HASH = s.ROW_HASH
WHEN NOT MATCHED THEN INSERT
    (LOCATION_ID, LOCATION_NAME, ADDRESS_LINE, DISTRICT_ID, DISTRICT_NAME,
     DISTRICT_CODE, STATE_ID, STATE_NAME, STATE_CODE,
     _SRC_FILE_NM, _BATCH_ID, _LOAD_TS, _ROW_HASH)
    VALUES
    (s.LOCATION_ID, s.LOCATION_NAME, s.ADDRESS_LINE, s.DISTRICT_ID, s.DISTRICT_NAME,
     s.DISTRICT_CODE, s.STATE_ID, s.STATE_NAME, s.STATE_CODE,
     s.SRC_FILE_NM, DATE '{{ ds }}', CURRENT_TIMESTAMP(), s.ROW_HASH);

-- 1.4 Recon
INSERT INTO control.C_BATCH_RECON
    (BATCH_ID, SRC_FILE_NM, TARGET_TABLE, BRONZE_CNT, TMP_CNT, REJ_CNT, VARIANCE, STATUS)
WITH b AS (SELECT COUNT(*) c FROM bronze.STG_STORE_MASTER WHERE BATCH_ID = DATE '{{ ds }}'),
     r AS (SELECT COUNT(*) c FROM control.C_REJ_TABLE
            WHERE BATCH_ID = DATE '{{ ds }}' AND TARGET_TABLE = 'TMP_STORE_MASTER'),
     t AS (
       SELECT COUNT(*) c FROM bronze.STG_STORE_MASTER s
        WHERE s.BATCH_ID = DATE '{{ ds }}'
          AND NOT EXISTS (
              SELECT 1 FROM control.C_REJ_TABLE r
               WHERE r.BATCH_ID = DATE '{{ ds }}' AND r.TARGET_TABLE = 'TMP_STORE_MASTER'
                 AND r.DETAILS:SRC_FILE_NM::VARCHAR = s.SRC_FILE_NM
                 AND r.DETAILS:SRC_ROW_NUM::NUMBER   = s.SRC_ROW_NUM))
SELECT DATE '{{ ds }}',
       COALESCE((SELECT MAX(SRC_FILE_NM) FROM bronze.STG_STORE_MASTER WHERE BATCH_ID = DATE '{{ ds }}'),'store_master'),
       'TMP_STORE_MASTER',
       b.c, t.c, r.c,
       b.c - (t.c + r.c),
       CASE WHEN b.c = (t.c + r.c) THEN 'PASSED' ELSE 'FAILED' END
FROM b, r, t;


