-- SILVER LOAD (flat script — no stored procedure)
-- Run via Airflow SQLExecuteQueryOperator with split_statements=True,
-- autocommit=False. Snowflake will treat the file as a sequence of
-- statements; the MERGE/INSERT DML is auto-wrapped in a transaction
-- by the connector when autocommit=False; DDL auto-commits regardless.
--
-- Batch id is bound as a placeholder :BATCH_ID by the driver — the
-- SQLExecuteQueryOperator passes `parameters` / `params` if you set them.
-- Simpler: use a single literal substitution here:
--   {{ ds }} is resolved by Airflow BEFORE the file runs, so the file
--   itself contains DATE '{{ ds }}'.
-- ============================================================================
