      AND s.TRANSACTION_ID IS NOT NULL
      AND TRY_TO_NUMBER(s.TRANSACTION_LINE_NUMBER) IS NOT NULL
      AND TRY_TO_DATE(s.SALES_DT,'YYYY-MM-DD') IS NOT NULL
      AND s.ITEM_ID IS NOT NULL AND s.LOCATION_ID IS NOT NULL
      AND s.CUSTOMER_ID IS NOT NULL AND s.CUSTOMER_NAME IS NOT NULL
      AND s.CUSTOMER_EMAIL IS NOT NULL AND s.CUSTOMER_PHONE IS NOT NULL
      AND TRY_TO_NUMBER(s.SLS_QTY) IS NOT NULL
      AND TRY_TO_NUMBER(s.SLS_AMT) IS NOT NULL
      AND TRY_TO_NUMBER(s.SLS_QTY) >= 0
      AND TRY_TO_NUMBER(s.SLS_AMT) >= 0
      AND EXISTS (SELECT 1 FROM silver.TMP_ITEM_MASTER i WHERE i.ITEM_ID = s.ITEM_ID)
      AND EXISTS (SELECT 1 FROM silver.TMP_STORE_MASTER st WHERE st.LOCATION_ID = s.LOCATION_ID)
      AND NOT EXISTS (
          SELECT 1
          FROM bronze.STG_POS_SALES d
          WHERE d.BATCH_ID = DATE '{{ ds }}'
          GROUP BY d.TRANSACTION_ID, TRY_TO_NUMBER(d.TRANSACTION_LINE_NUMBER)
          HAVING COUNT(*) > 1
          AND d.TRANSACTION_ID = s.TRANSACTION_ID
          AND TRY_TO_NUMBER(d.TRANSACTION_LINE_NUMBER) = TRY_TO_NUMBER(s.TRANSACTION_LINE_NUMBER)
      )
) s
ON t.TRANSACTION_ID = s.TRANSACTION_ID
AND t.TRANSACTION_LINE_NUMBER = s.TRANSACTION_LINE_NUMBER
