INSERT INTO control.C_REJ_TABLE
    (SRC_FILE_NM, BATCH_ID, TARGET_TABLE, REASON_CODE, REASON, DETAILS)
SELECT s.SRC_FILE_NM, DATE '{{ ds }}', 'TMP_ITEM_MASTER',
       'DUP_BUSINESS_KEY',
       'Composite (ITEM_ID, CLASS_ID, DEPARTMENT_ID) duplicated within batch',
       OBJECT_CONSTRUCT(s.*)
FROM bronze.STG_ITEM_MASTER s
JOIN (
    SELECT ITEM_ID, CLASS_ID, DEPARTMENT_ID
    FROM bronze.STG_ITEM_MASTER
    WHERE BATCH_ID = DATE '{{ ds }}'
    GROUP BY ITEM_ID, CLASS_ID, DEPARTMENT_ID HAVING COUNT(*) > 1
) d ON  d.ITEM_ID = s.ITEM_ID
    AND d.CLASS_ID = s.CLASS_ID
    AND d.DEPARTMENT_ID = s.DEPARTMENT_ID
WHERE s.BATCH_ID = DATE '{{ ds }}';

MERGE INTO silver.TMP_ITEM_MASTER t
USING (
    SELECT
        s.ITEM_ID, s.ITEM_NAME, s.COLOR, s.SIZE,
        s.CLASS_ID, s.CLASS_NAME, s.CLASS_DESCRIPTION,
        s.DEPARTMENT_ID, s.DEPARTMENT_NAME, s.DEPARTMENT_MANAGER_NAME,
        s.COMPANY_ID, s.COMPANY_NAME, s.COMPANY_TYPE,
        s.SRC_FILE_NM,
        MD5(
            COALESCE(s.ITEM_ID,'')||'|'||COALESCE(s.ITEM_NAME,'')||'|'||
            COALESCE(s.COLOR,'')||'|'||COALESCE(s.SIZE,'')||'|'||
            COALESCE(s.CLASS_ID,'')||'|'||COALESCE(s.CLASS_NAME,'')||'|'||
            COALESCE(s.CLASS_DESCRIPTION,'')||'|'||COALESCE(s.DEPARTMENT_ID,'')||'|'||
            COALESCE(s.DEPARTMENT_NAME,'')||'|'||COALESCE(s.DEPARTMENT_MANAGER_NAME,'')||'|'||
            COALESCE(s.COMPANY_ID,'')||'|'||COALESCE(s.COMPANY_NAME,'')||'|'||
            COALESCE(s.COMPANY_TYPE,'')
        ) AS ROW_HASH
    FROM bronze.STG_ITEM_MASTER s
    WHERE s.BATCH_ID = DATE '{{ ds }}'
      AND s.ITEM_ID IS NOT NULL AND s.ITEM_NAME IS NOT NULL
      AND s.COLOR IS NOT NULL AND s.SIZE IS NOT NULL
      AND s.CLASS_ID IS NOT NULL AND s.CLASS_NAME IS NOT NULL
      AND s.CLASS_DESCRIPTION IS NOT NULL AND s.DEPARTMENT_ID IS NOT NULL
      AND s.DEPARTMENT_NAME IS NOT NULL AND s.DEPARTMENT_MANAGER_NAME IS NOT NULL
      AND s.COMPANY_ID IS NOT NULL AND s.COMPANY_NAME IS NOT NULL
      AND s.COMPANY_TYPE IS NOT NULL
      AND (s.ITEM_ID, s.CLASS_ID, s.DEPARTMENT_ID) NOT IN (
          SELECT ITEM_ID, CLASS_ID, DEPARTMENT_ID
          FROM bronze.STG_ITEM_MASTER
          WHERE BATCH_ID = DATE '{{ ds }}'
          GROUP BY ITEM_ID, CLASS_ID, DEPARTMENT_ID HAVING COUNT(*) > 1
      )
) s
ON  t.ITEM_ID = s.ITEM_ID
AND t.CLASS_ID = s.CLASS_ID
AND t.DEPARTMENT_ID = s.DEPARTMENT_ID
WHEN MATCHED AND t._ROW_HASH <> s.ROW_HASH THEN UPDATE SET
    ITEM_NAME = s.ITEM_NAME, COLOR = s.COLOR, SIZE = s.SIZE,
    CLASS_NAME = s.CLASS_NAME, CLASS_DESCRIPTION = s.CLASS_DESCRIPTION,
    DEPARTMENT_NAME = s.DEPARTMENT_NAME,
    DEPARTMENT_MANAGER_NAME = s.DEPARTMENT_MANAGER_NAME,
    COMPANY_ID = s.COMPANY_ID, COMPANY_NAME = s.COMPANY_NAME,
    COMPANY_TYPE = s.COMPANY_TYPE,
    _SRC_FILE_NM = s.SRC_FILE_NM, _BATCH_ID = DATE '{{ ds }}',
    _LOAD_TS = CURRENT_TIMESTAMP(), _ROW_HASH = s.ROW_HASH
WHEN NOT MATCHED THEN INSERT
    (ITEM_ID, ITEM_NAME, COLOR, SIZE, CLASS_ID, CLASS_NAME, CLASS_DESCRIPTION,
     DEPARTMENT_ID, DEPARTMENT_NAME, DEPARTMENT_MANAGER_NAME,
     COMPANY_ID, COMPANY_NAME, COMPANY_TYPE,
     _SRC_FILE_NM, _BATCH_ID, _LOAD_TS, _ROW_HASH)
    VALUES
    (s.ITEM_ID, s.ITEM_NAME, s.COLOR, s.SIZE, s.CLASS_ID, s.CLASS_NAME, s.CLASS_DESCRIPTION,
     s.DEPARTMENT_ID, s.DEPARTMENT_NAME, s.DEPARTMENT_MANAGER_NAME,
     s.COMPANY_ID, s.COMPANY_NAME, s.COMPANY_TYPE,
     s.SRC_FILE_NM, DATE '{{ ds }}', CURRENT_TIMESTAMP(), s.ROW_HASH);

INSERT INTO control.C_BATCH_RECON
    (BATCH_ID, SRC_FILE_NM, TARGET_TABLE, BRONZE_CNT, TMP_CNT, REJ_CNT, VARIANCE, STATUS)
WITH b AS (SELECT COUNT(*) c FROM bronze.STG_ITEM_MASTER WHERE BATCH_ID = DATE '{{ ds }}'),
     r AS (SELECT COUNT(*) c FROM control.C_REJ_TABLE
            WHERE BATCH_ID = DATE '{{ ds }}' AND TARGET_TABLE = 'TMP_ITEM_MASTER'),
     t AS (
       SELECT COUNT(*) c FROM bronze.STG_ITEM_MASTER s
        WHERE s.BATCH_ID = DATE '{{ ds }}'
          AND NOT EXISTS (
              SELECT 1 FROM control.C_REJ_TABLE r
               WHERE r.BATCH_ID = DATE '{{ ds }}' AND r.TARGET_TABLE = 'TMP_ITEM_MASTER'
                 AND r.DETAILS:SRC_FILE_NM::VARCHAR = s.SRC_FILE_NM
                 AND r.DETAILS:SRC_ROW_NUM::NUMBER   = s.SRC_ROW_NUM))
SELECT DATE '{{ ds }}',
       COALESCE((SELECT MAX(SRC_FILE_NM) FROM bronze.STG_ITEM_MASTER WHERE BATCH_ID = DATE '{{ ds }}'),'item_master'),
       'TMP_ITEM_MASTER',
       b.c, t.c, r.c,
       b.c - (t.c + r.c),
       CASE WHEN b.c = (t.c + r.c) THEN 'PASSED' ELSE 'FAILED' END
FROM b, r, t;