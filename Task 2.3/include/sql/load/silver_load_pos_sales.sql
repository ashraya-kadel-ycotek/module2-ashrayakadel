INSERT INTO control.C_REJ_TABLE
    (SRC_FILE_NM, BATCH_ID, TARGET_TABLE, REASON_CODE, REASON, DETAILS)
SELECT s.SRC_FILE_NM, DATE '{{ ds }}', 'TMP_POS_SALES',
       'DUP_BUSINESS_KEY',
       '(TRANSACTION_ID, TRANSACTION_LINE_NUMBER) duplicated within batch',
       OBJECT_CONSTRUCT(s.*)
FROM bronze.STG_POS_SALES s
JOIN (
    SELECT TRANSACTION_ID, TRY_TO_NUMBER(TRANSACTION_LINE_NUMBER) AS LN
    FROM bronze.STG_POS_SALES
    WHERE BATCH_ID = DATE '{{ ds }}'
    GROUP BY 1,2 HAVING COUNT(*) > 1
