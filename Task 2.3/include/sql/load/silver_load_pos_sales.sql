-- 4.6 MERGE valid POS sales
MERGE INTO silver.TMP_POS_SALES t
USING (
    SELECT
        s.TRANSACTION_ID,
        TRY_TO_NUMBER(s.TRANSACTION_LINE_NUMBER) AS TRANSACTION_LINE_NUMBER,
        TRY_TO_DATE(s.SALES_DT,'YYYY-MM-DD') AS SALES_DT,
        s.ITEM_ID, s.LOCATION_ID,
        s.CUSTOMER_ID, s.CUSTOMER_NAME, s.CUSTOMER_EMAIL, s.CUSTOMER_PHONE,
        TRY_TO_NUMBER(s.SLS_QTY) AS SLS_QTY,
        TRY_TO_NUMBER(s.SLS_AMT) AS SLS_AMT,
        s.SRC_FILE_NM,
        MD5(
            COALESCE(s.TRANSACTION_ID,'')||'|'||
            TO_VARCHAR(TRY_TO_NUMBER(s.TRANSACTION_LINE_NUMBER))||'|'||
            TO_VARCHAR(TRY_TO_DATE(s.SALES_DT,'YYYY-MM-DD'))||'|'||
            COALESCE(s.ITEM_ID,'')||'|'||COALESCE(s.LOCATION_ID,'')||'|'||
            COALESCE(s.CUSTOMER_ID,'')||'|'||COALESCE(s.CUSTOMER_NAME,'')||'|'||
            COALESCE(s.CUSTOMER_EMAIL,'')||'|'||COALESCE(s.CUSTOMER_PHONE,'')||'|'||
            TO_VARCHAR(TRY_TO_NUMBER(s.SLS_QTY))||'|'||
            TO_VARCHAR(TRY_TO_NUMBER(s.SLS_AMT))
        ) AS ROW_HASH
    FROM bronze.STG_POS_SALES s
    WHERE s.BATCH_ID = DATE '{{ ds }}'
      AND s.TRANSACTION_ID IS NOT NULL
      AND TRY_TO_NUMBER(s.TRANSACTION_LINE_NUMBER) IS NOT NULL
      AND TRY_TO_DATE(s.SALES_DT,'YYYY-MM-DD') IS NOT NULL
      AND s.ITEM_ID IS NOT NULL AND s.LOCATION_ID IS NOT NULL
      AND s.CUSTOMER_ID IS NOT NULL AND s.CUSTOMER_NAME IS NOT NULL
      AND s.CUSTOMER_EMAIL IS NOT NULL AND s.CUSTOMER_PHONE IS NOT NULL
      AND TRY_TO_NUMBER(s.SLS_QTY) IS NOT NULL
      AND TRY_TO_NUMBER(s.SLS_AMT) IS NOT NULL
      AND TRY_TO_NUMBER(s.SLS_QTY) >= 0
      AND TRY_TO_NUMBER(s.SLS_AMT) >= 0
      AND EXISTS (SELECT 1 FROM silver.TMP_ITEM_MASTER i WHERE i.ITEM_ID = s.ITEM_ID)
      AND EXISTS (SELECT 1 FROM silver.TMP_STORE_MASTER st WHERE st.LOCATION_ID = s.LOCATION_ID)
      AND NOT EXISTS (
          SELECT 1
          FROM bronze.STG_POS_SALES d
          WHERE d.BATCH_ID = DATE '{{ ds }}'
          GROUP BY d.TRANSACTION_ID, TRY_TO_NUMBER(d.TRANSACTION_LINE_NUMBER)
          HAVING COUNT(*) > 1
          AND d.TRANSACTION_ID = s.TRANSACTION_ID
          AND TRY_TO_NUMBER(d.TRANSACTION_LINE_NUMBER) = TRY_TO_NUMBER(s.TRANSACTION_LINE_NUMBER)
      )
) s
ON t.TRANSACTION_ID = s.TRANSACTION_ID
AND t.TRANSACTION_LINE_NUMBER = s.TRANSACTION_LINE_NUMBER
WHEN MATCHED AND t._ROW_HASH <> s.ROW_HASH THEN UPDATE SET
    SALES_DT = s.SALES_DT,
    ITEM_ID = s.ITEM_ID,
    LOCATION_ID = s.LOCATION_ID,
    CUSTOMER_ID = s.CUSTOMER_ID,
    CUSTOMER_NAME = s.CUSTOMER_NAME,
    CUSTOMER_EMAIL = s.CUSTOMER_EMAIL,
    CUSTOMER_PHONE = s.CUSTOMER_PHONE,
    SLS_QTY = s.SLS_QTY,
    SLS_AMT = s.SLS_AMT,
    _SRC_FILE_NM = s.SRC_FILE_NM,
    _BATCH_ID = DATE '{{ ds }}',
    _LOAD_TS = CURRENT_TIMESTAMP(),
    _ROW_HASH = s.ROW_HASH
WHEN NOT MATCHED THEN INSERT
    (TRANSACTION_ID, TRANSACTION_LINE_NUMBER, SALES_DT, ITEM_ID, LOCATION_ID,
     CUSTOMER_ID, CUSTOMER_NAME, CUSTOMER_EMAIL, CUSTOMER_PHONE, SLS_QTY, SLS_AMT,
     _SRC_FILE_NM, _BATCH_ID, _LOAD_TS, _ROW_HASH)
VALUES
    (s.TRANSACTION_ID, s.TRANSACTION_LINE_NUMBER, s.SALES_DT, s.ITEM_ID, s.LOCATION_ID,
     s.CUSTOMER_ID, s.CUSTOMER_NAME, s.CUSTOMER_EMAIL, s.CUSTOMER_PHONE, s.SLS_QTY, s.SLS_AMT,
     s.SRC_FILE_NM, DATE '{{ ds }}', CURRENT_TIMESTAMP(), s.ROW_HASH);

-- 4.7 Recon
INSERT INTO control.C_BATCH_RECON
    (BATCH_ID, SRC_FILE_NM, TARGET_TABLE, BRONZE_CNT, TMP_CNT, REJ_CNT, VARIANCE, STATUS)
WITH b AS (SELECT COUNT(*) c FROM bronze.STG_POS_SALES WHERE BATCH_ID = DATE '{{ ds }}'),
     r AS (SELECT COUNT(*) c FROM control.C_REJ_TABLE
            WHERE BATCH_ID = DATE '{{ ds }}' AND TARGET_TABLE = 'TMP_POS_SALES'),
     t AS (
       SELECT COUNT(*) c FROM bronze.STG_POS_SALES s
        WHERE s.BATCH_ID = DATE '{{ ds }}'
          AND NOT EXISTS (
              SELECT 1 FROM control.C_REJ_TABLE r
               WHERE r.BATCH_ID = DATE '{{ ds }}' AND r.TARGET_TABLE = 'TMP_POS_SALES'
                 AND r.DETAILS:SRC_FILE_NM::VARCHAR = s.SRC_FILE_NM
                 AND r.DETAILS:SRC_ROW_NUM::NUMBER = s.SRC_ROW_NUM))
SELECT DATE '{{ ds }}',
       COALESCE((SELECT MAX(SRC_FILE_NM) FROM bronze.STG_POS_SALES WHERE BATCH_ID = DATE '{{ ds }}'),'pos_sales'),
       'TMP_POS_SALES', b.c, t.c, r.c,
       b.c - (t.c + r.c),
       CASE WHEN b.c = (t.c + r.c) THEN 'PASSED' ELSE 'FAILED' END
FROM b, r, t;